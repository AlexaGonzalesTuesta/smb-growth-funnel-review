"""Evaluation suite. Checks that the data matches the published Kaggle files, that the funnel reconciles,
and that both models beat their baselines on months they never saw. Fails (exit 1) if any check fails.

    python -m evals.run_evals
"""
import json
import sys

from growth import activation, config, db, funnel, risk

# Row counts of the original Kaggle files. If a file is swapped or truncated, the suite fails.
KAGGLE_ROWS = {
    "leads": 8000, "deals": 842, "sellers": 3095,
}


def checks():
    con = db.connect()
    results = []

    def add(name, value, passed, target):
        results.append({"check": name, "value": value, "target": target, "passed": bool(passed)})

    for table, rows in KAGGLE_ROWS.items():
        n = con.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        add(f"{table} rows match Kaggle", n, n == rows, rows)
    orders = con.sql("SELECT COUNT(DISTINCT order_id) FROM read_csv_auto("
                     f"'{config.RAW.as_posix()}/olist_orders_dataset.csv.gz', header=true)").fetchone()[0]
    add("orders rows match Kaggle", orders, orders == 99441, 99441)

    lf = funnel.lead_funnel(con)
    s = funnel.summary(lf)
    add("funnel reconciles: activated <= won <= leads", f"{s['activated']} <= {s['won']} <= {s['leads']}",
        s["activated"] <= s["won"] <= s["leads"], "true")
    gmv_check = con.sql(f"""SELECT SUM(s.gmv) FROM lead_funnel f JOIN deals d USING (mql_id)
        JOIN sales s ON s.seller_id = d.seller_id AND s.ts >= d.won_date
         AND s.ts < d.won_date + INTERVAL {config.ACTIVATION_DAYS} DAY
        WHERE f.won""").fetchone()[0]
    add("funnel GMV reconciles to raw order items", round(s["gmv"], 2), abs(gmv_check - s["gmv"]) < 0.01,
        round(gmv_check, 2))
    last = con.sql(f"SELECT MAX(won_date + INTERVAL {config.ACTIVATION_DAYS} DAY) FROM deal_outcomes "
                   f"WHERE won_date <= TIMESTAMP '{config.WIN_CUTOFF} 23:59:59'").fetchone()[0]
    add("every counted deal has a full activation window", str(last.date()), str(last.date()) <= config.DATA_END,
        f"<= {config.DATA_END}")

    r = risk.evaluate(con)["metrics"]
    add("at-risk model AUC on unseen snapshot", round(r["auc"], 3), r["auc"] >= 0.72, ">= 0.72")
    add("at-risk lift (flagged vs all)", round(r["lift"], 2), r["lift"] >= 2.0, ">= 2.0x")
    add("at-risk precision beats the spreadsheet rule", round(r["precision_flagged"], 3),
        r["precision_flagged"] > r["rule_precision"], f"> {r['rule_precision']:.3f}")

    a = activation.evaluate(funnel.won_deals(con))
    add("activation-at-signing model AUC on later deals", round(a["auc"], 3), a["auc"] >= 0.62, ">= 0.62")
    return results, r, a


def main() -> int:
    results, r, a = checks()
    config.REPORTS.mkdir(exist_ok=True)
    (config.REPORTS / "metrics.json").write_text(json.dumps({"checks": results, "risk": r, "activation": a},
                                                            indent=2, default=float), encoding="utf-8")
    lines = ["# Evaluation report", "", "Generated by `python -m evals.run_evals`. All data is the real Olist data.",
             "", "| Check | Result | Target | Pass |", "|---|---|---|---|"]
    for x in results:
        lines.append(f"| {x['check']} | {x['value']} | {x['target']} | {'yes' if x['passed'] else 'NO'} |")
    lines += ["", "## At-risk seller model", "",
              f"Trained on {r['train_sellers']} active sellers as of {config.RISK_TRAIN_SNAPSHOT}, tested on "
              f"{r['test_sellers']} active sellers as of {config.RISK_TEST_SNAPSHOT}. Outcome: no sale in the next "
              f"{config.RISK_HORIZON_DAYS} days.", "",
              "| Measure | Model (top 20%) | Spreadsheet rule (no sale in 21 days or orders halved) |", "|---|---|---|",
              f"| Sellers flagged | {r['flagged']} | {r['rule_flagged']} |",
              f"| Flagged sellers that went dark | {r['precision_flagged']:.1%} | {r['rule_precision']:.1%} |",
              f"| Share of all dark sellers caught | {r['recall']:.1%} | {r['rule_recall']:.1%} |",
              f"| Base rate (all active sellers) | {r['base_rate']:.1%} | {r['base_rate']:.1%} |",
              "", f"ROC AUC: {r['auc']:.3f}. On a list of about the same size, the model's hit rate is "
              f"{r['precision_flagged'] / r['rule_precision']:.1f}x the rule's and it catches more of the sellers who stop selling.",
              "", "## Activation-at-signing model", "",
              f"Trained on {a['train_deals']} deals won Jan-Mar 2018, tested on {a['test_deals']} deals won Apr-May 2018. "
              f"ROC AUC {a['auc']:.3f}. Sellers in the lowest-scored third activated {a['activation_lowest_third']:.0%} "
              f"of the time versus {a['activation_highest_third']:.0%} in the highest third. This is a modest model: "
              "good enough to order onboarding calls, not to decide who gets signed.", ""]
    (config.REPORTS / "eval_report.md").write_text("\n".join(lines), encoding="utf-8")
    failed = [x for x in results if not x["passed"]]
    for x in results:
        print(f"[{'PASS' if x['passed'] else 'FAIL'}] {x['check']}: {x['value']} (target {x['target']})")
    print(f"{len(results) - len(failed)}/{len(results)} checks passed.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
